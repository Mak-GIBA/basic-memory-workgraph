#!/usr/bin/env bash
# Codex Office Workbench 1.0.0 -- single-file, per-user installer.
# Linux/WSL2 (glibc) x64/ARM64; macOS asset paths included, not tested here.
# No sibling files required. Python 3.11+ and local Codex are prerequisites.
#
# Default: dry-run. --apply fetches fixed OfficeCLI/Python dependencies.
# Existing ECC, Basic Memory, hooks, AGENTS.md and shell settings are untouched.
# Codex config.toml changes ONLY with explicit --with-mcp / mcp-enable.
# No fonts are embedded. --install-system-deps is an explicit OS-level action.
#
# bash install_codex_office.sh --dry-run
# bash install_codex_office.sh --apply
# bash install_codex_office.sh --doctor
# bash install_codex_office.sh --apply --force
# bash install_codex_office.sh --self-test
# bash install_codex_office.sh --extract /tmp/codex-office-source
#
# Read/extract before running downloaded code. Embedded checksum detects
# corruption, NOT publisher authenticity. Run as your ordinary user; no sudo.
set -euo pipefail
PY="${PYTHON_BIN:-}"
if [[ -z "$PY" ]]; then
  for candidate in python3 python3.13 python3.12 python3.11; do
    if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3,11) else 1)' 2>/dev/null; then
      PY="$candidate"; break
    fi
  done
fi
if [[ -z "$PY" ]] || ! "$PY" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3,11) else 1)' 2>/dev/null; then
  echo 'ERROR: Python 3.11+ required. Set PYTHON_BIN to an appropriate interpreter.' >&2
  exit 2
fi
export PYTHONDONTWRITEBYTECODE=1
